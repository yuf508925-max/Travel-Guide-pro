def describe(code: int | None) -> tuple[str, str]:
    """天气代码 → (中文, 图标key)。没见过的代码不报错，给个兜底"""
    return WMO.get(int(code or 0), ("未知天气", "cloudy"))


def _clean_city(raw: str) -> str:
    """去掉空格和「市 / 省 / 自治区」这类后缀，方便查表"""
    name = (raw or "").strip().replace(" ", "")
    for suffix in ("特别行政区", "自治区", "省", "市"):
        if len(name) > 2 and name.endswith(suffix):
            name = name[: -len(suffix)]
            break
    return name


def _clean_region(raw: str) -> str:
    """省份规范成表里用的短名：广西壮族自治区 → 广西、新疆维吾尔自治区 → 新疆"""
    name = (raw or "").strip().replace(" ", "")
    for suffix in (
        "特别行政区",
        "壮族自治区",
        "回族自治区",
        "维吾尔自治区",
        "自治区",
        "省",
        "市",
    ):
        if name.endswith(suffix) and len(name) > len(suffix):
            name = name[: -len(suffix)]
            break
    return name


def _fetch_json_sync(url: str, params: dict) -> dict:
    """同步请求一次上游（放在线程里跑，别堵住事件循环）

    只用标准库 urllib：这套接口在哪个 Python 环境里都能跑，
    不用为了一次天气请求去多装一个 HTTP 客户端。
    """
    full_url = f"{url}?{urllib.parse.urlencode(params)}"
    request = urllib.request.Request(
        full_url,
        headers={"User-Agent": "fufu-travel/0.1 (+weather panel)"},
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT) as response:
            payload = response.read()
    except urllib.error.HTTPError as exc:      # 上游返回 4xx/5xx
        raise WeatherUnavailable(f"天气服务返回了 {exc.code}") from exc
    except (urllib.error.URLError, TimeoutError, OSError) as exc:  # 断网 / DNS / 超时
        raise WeatherUnavailable("天气服务连不上，检查一下网络") from exc

    try:
        return json.loads(payload.decode("utf-8"))
    except (ValueError, UnicodeDecodeError) as exc:
        raise WeatherUnavailable("天气服务返回的数据看不懂") from exc


async def _get_json(url: str, params: dict) -> dict:
    """异步版 _fetch_json_sync：扔到线程池，不阻塞其它请求"""
    return await asyncio.to_thread(_fetch_json_sync, url, params)


async def geocode(city: str, province: str = "") -> tuple[str, float, float, str]:
    """(省, 市) → (标准名, 纬度, 经度, 所属行政区)

    先查本地表（表里的 region 就是省份）；查不到再拿「省+市」和「市」
    分别去 Open-Meteo 地理编码试一次，按"中国优先 + 人口最多"挑最像的。
    省份主要用来消歧和兜底；表里能直接命中的城市，以表里的省份为准。
    """
    name = _clean_city(city)
    name = ALIASES.get(name, name)
    if not name:
        raise CityNotFound(city)

    hit = CITIES.get(name)
    if hit:
        lat, lon, region = hit
        return name, lat, lon, region

    # ---- 表里没有 → 在线兜底：先「省+市」，再只用市名 ----
    region = _clean_region(province)
    queries = [f"{region}{name}", name] if region else [name]

    for query in queries:
        data = await _get_json(
            GEOCODE_URL,
            {"name": query, "count": 10, "language": "zh", "format": "json"},
        )
        results = data.get("results") or []
        if not results:
            continue

        # 同名的地方很多（「青岛」在辽宁也有一个村），按"中国优先 + 人口最多"挑
        def rank(item: dict) -> tuple[int, int]:
            is_cn = 1 if item.get("country_code") == "CN" else 0
            return (is_cn, int(item.get("population") or 0))

        best = max(results, key=rank)
        label = best.get("name") or name
        admin = best.get("admin1") or best.get("country") or ""
        return label, float(best["latitude"]), float(best["longitude"]), admin

    raise CityNotFound(city)


async def get_weather(city: str, province: str = "", days: int = 7) -> dict:
    """查天气：返回当前天气 + 未来 days 天的预报（已整理成前端好用的结构）"""
    label, lat, lon, region = await geocode(city, province)

    data = await _get_json(
        FORECAST_URL,
        {
            "latitude": lat,
            "longitude": lon,
            "current": "temperature_2m,weather_code,wind_speed_10m,relative_humidity_2m",
            "daily": ",".join(
                [
                    "weather_code",
                    "temperature_2m_max",
                    "temperature_2m_min",
                    "precipitation_probability_max",
                    "wind_speed_10m_max",
                ]
            ),
            "timezone": "auto",
            "forecast_days": days,
        },
    )

    daily = data.get("daily") or {}
    dates = daily.get("time") or []
    if not dates:
        raise WeatherUnavailable("天气服务没返回预报数据")

    today = dt.date.today()
    forecast: list[dict] = []
    for idx, date_str in enumerate(dates):
        code = _pick(daily.get("weather_code"), idx)
        desc, icon = describe(code)
        date_obj = today
        try:
            date_obj = dt.date.fromisoformat(date_str)
        except ValueError:
            pass
        forecast.append(
            {
                "date": date_str,
                "weekday": "今天" if date_obj == today else WEEKDAYS[date_obj.weekday()],
                "code": code,
                "desc": desc,
                "icon": icon,
                "temp_max": _round(_pick(daily.get("temperature_2m_max"), idx)),
                "temp_min": _round(_pick(daily.get("temperature_2m_min"), idx)),
                "rain_prob": _pick(daily.get("precipitation_probability_max"), idx),
                "wind_max": _round(_pick(daily.get("wind_speed_10m_max"), idx)),
            }
        )

    current = data.get("current") or {}
    cur_code = current.get("weather_code")
    cur_desc, cur_icon = describe(cur_code)

    return {
        "city": label,
        "region": region,
        "latitude": lat,
        "longitude": lon,
        "timezone": data.get("timezone"),
        "updated_at": dt.datetime.now().isoformat(timespec="minutes"),
        "current": {
            "temp": _round(current.get("temperature_2m")),
            "desc": cur_desc,
            "icon": cur_icon,
            "wind": _round(current.get("wind_speed_10m")),
            "humidity": current.get("relative_humidity_2m"),
        },
        "days": forecast,
    }


def _pick(values, index: int):
    """从日数组里安全地取第 index 个值（上游偶尔会少几列）"""
    if not isinstance(values, list) or index >= len(values):
        return None
    return values[index]


def _round(value) -> float | None:
    """保留一位小数；None 原样返回，前端据此显示「--」"""
    try:
        return round(float(value), 1)
    except (TypeError, ValueError):
        return None
